#!/usr/bin/env node
// Deterministic production export. Masters retain their generated transparency;
// this pipeline only fits them into the game's existing 256px sprite format.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, join } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { createCanvas, loadImage } = createRequire(import.meta.url)(process.env.ACORNAUT_CANVAS || '@napi-rs/canvas');
const source = join(root, 'art-src/zone-identity');
const { assets } = JSON.parse(readFileSync(join(source, 'prompts.json')));
const partial = process.argv.includes('--partial');
const missing = assets.filter(a => !existsSync(join(source, `${a.id}.png`)));
if (missing.length && !partial) throw new Error(`Zone masters missing: ${missing.map(a => a.id).join(', ')}`);
const hash = b => createHash('sha256').update(b).digest('hex');
const results = [];
for (const a of assets) {
  const master = join(source, `${a.id}.png`);
  if (!existsSync(master)) continue;
  const image = await loadImage(master);
  const canvas = createCanvas(256, 256), c = canvas.getContext('2d');
  const scale = 256 / Math.max(image.width, image.height);
  c.imageSmoothingEnabled = true; c.imageSmoothingQuality = 'high';
  c.drawImage(image, (256 - image.width * scale) / 2, (256 - image.height * scale) / 2, image.width * scale, image.height * scale);
  const pixels = c.getImageData(0, 0, 256, 256).data;
  let clear = 0, solid = 0; const rgb = [0, 0, 0];
  let minX = 256, minY = 256, maxX = 0, maxY = 0;
  for (let i = 0; i < pixels.length; i += 4) {
    const alpha = pixels[i + 3];
    if (!alpha) clear++;
    if (alpha >= 80) {
      solid++; for (let k = 0; k < 3; k++) rgb[k] += pixels[i + k] / 255;
      const x = i / 4 % 256, y = Math.floor(i / 4 / 256);
      minX = Math.min(minX, x); minY = Math.min(minY, y); maxX = Math.max(maxX, x); maxY = Math.max(maxY, y);
    }
  }
  if (clear < 10000 || solid < 3000 || minX < 2 || minY < 2 || maxX > 253 || maxY > 253)
    throw new Error(`${a.id}: transparency, solid footprint or edge-padding check failed`);
  const folder = a.type === 'planet' ? 'planets' : 'debris';
  const output = join(root, `docs/art/${folder}/${a.index}.png`);
  mkdirSync(dirname(output), { recursive: true });
  const buffer = canvas.toBuffer('image/png'); writeFileSync(output, buffer);
  results.push({ id: a.id, name: a.name, type: a.type, index: a.index, zone: a.zone,
    master: `art-src/zone-identity/${a.id}.png`, output: `docs/art/${folder}/${a.index}.png`,
    masterSha256: hash(readFileSync(master)), sha256: hash(buffer), bytes: buffer.length,
    rgb: rgb.map(v => Number((v / solid).toFixed(4))),
    solidPixels: solid, transparentPixels: clear, bounds: [minX, minY, maxX, maxY] });
}
const colors = results.filter(a => a.type === 'planet').sort((a,b) => a.index - b.index);
// Partial mode is for local visual review while masters are being produced.
// A normal shipping export refuses missing masters before touching outputs.
writeFileSync(join(root, 'illustrated-src/game/zone-planet-colors.ts'),
  '// Generated by export-zone-art.mjs from production sprite pixels.\n'
  + 'export const NEW_PLANET_RGB: [number, number, number][] = '
  + JSON.stringify(Array.from({ length: 101 }, (_, i) => colors.find(a => a.index === i + 33)?.rgb ?? null), null, 2) + ';\n');
if (!partial) {
  if (colors.length !== 101 || results.length !== 129) throw new Error('Approved asset roster is incomplete');
  writeFileSync(join(source, 'shipping-manifest.json'), JSON.stringify({ exporter: 'illustrated-src/export-zone-art.mjs', assets: results }, null, 2) + '\n');
}
console.log(`Zone art: ${results.length}/129 exported; ${missing.length} masters pending${partial ? ' (partial local preview)' : ''}`);

// Key and pack the generated, separated puppet parts using the game's existing
// green-matte export convention. No anatomical drawing is synthesized here.
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdirSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const require=createRequire(import.meta.url);
const {createCanvas,loadImage}=require(process.env.ACORNAUT_CANVAS||'@napi-rs/canvas');
const root=fileURLToPath(new URL('../',import.meta.url));
const im=await loadImage(root+'art-src/vanguard/maneuver/parts-keyed.png');
const W=im.width,H=im.height,matte=createCanvas(W,H),g=matte.getContext('2d');
g.drawImage(im,0,0);const pixels=g.getImageData(0,0,W,H),d=pixels.data;
for(let i=0;i<d.length;i+=4){
  const m=Math.max(d[i],d[i+2]),excess=d[i+1]-m;
  if(excess>18){const a=Math.max(0,Math.min(1,1-(excess-18)/145));d[i+1]=Math.min(d[i+1],m+8);d[i+3]=Math.round(a*255);}
}
g.putImageData(pixels,0,0);
const seen=new Uint8Array(W*H),labels=new Uint16Array(W*H),queue=new Int32Array(W*H),parts=[];
for(let start=0;start<W*H;start++){
  if(seen[start]||d[start*4+3]<20)continue;
  let read=0,write=1;queue[0]=start;seen[start]=1;
  let left=W,top=H,right=0,bottom=0;
  const add=p=>{if(!seen[p]&&d[p*4+3]>=20){seen[p]=1;queue[write++]=p;}};
  while(read<write){const p=queue[read++],x=p%W,y=Math.floor(p/W);
    left=Math.min(left,x);top=Math.min(top,y);right=Math.max(right,x);bottom=Math.max(bottom,y);
    if(x)add(p-1);if(x+1<W)add(p+1);if(y)add(p-W);if(y+1<H)add(p+W);
  }
  if(write>5000){const label=parts.length+1;for(let i=0;i<write;i++)labels[queue[i]]=label;
    parts.push({left,top,right,bottom,area:write,label});}
}
assert.equal(parts.length,12,'twelve complete isolated body parts');
parts.sort((a,b)=>Math.floor((a.top+a.bottom)/2/(H/3))-Math.floor((b.top+b.bottom)/2/(H/3))||a.left-b.left);
const names=['head','torso','nearUpperArm','nearForearm','farUpperArm','farForearm',
  'nearThigh','nearShin','farThigh','farShin','tail','tailRelaxed'];
// Measured source-joint positions, independent of texture cell normalization.
const joints=[[[177,440],[230,292]],[[560,166],[551,419]],
  [[829,126],[874,397]],[[1145,135],[1146,388]],
  [[206,536],[142,755]],[[460,531],[458,773]],
  [[764,516],[784,753]],[[1096,525],[1124,778]],
  [[177,886],[146,1112]],[[432,886],[465,1133]],
  [[903,1137],[674,910]],[[1210,1140],[1008,938]]];
const atlas=createCanvas(1024,768),ctx=atlas.getContext('2d'),manifest=[];
for(let n=0;n<12;n++){
  const p=parts[n],sx=p.left-2,sy=p.top-2,sw=p.right-p.left+5,sh=p.bottom-p.top+5;
  const scale=Math.min(240/sw,240/sh),dx=(256-sw*scale)/2,dy=(256-sh*scale)/2;
  // Tail bounds overlap rectangularly: select only this connected component,
  // retaining its two-pixel antialias fringe. A plain crop imports the other
  // tail's tip even though the silhouettes themselves never touch.
  const isolated=createCanvas(sw,sh),ig=isolated.getContext('2d'),ip=ig.createImageData(sw,sh);
  for(let y=0;y<sh;y++)for(let x=0;x<sw;x++){
    const gx=sx+x,gy=sy+y,si=gy*W+gx;let own=labels[si]===p.label;
    if(!own&&d[si*4+3]>0&&!labels[si])for(let oy=-2;oy<=2&&!own;oy++)for(let ox=-2;ox<=2&&!own;ox++)own=labels[(gy+oy)*W+gx+ox]===p.label;
    if(own)for(let ch=0;ch<4;ch++)ip.data[(y*sw+x)*4+ch]=d[si*4+ch];
  }
  ig.putImageData(ip,0,0);
  const cell=createCanvas(256,256),cg=cell.getContext('2d');
  cg.drawImage(isolated,0,0,sw,sh,dx,dy,sw*scale,sh*scale);
  const data=cg.getImageData(0,0,256,256).data;
  for(let i=0;i<256;i++)for(const k of [i,255*256+i,i*256,i*256+255])assert(data[k*4+3]<16,`unclipped ${names[n]}`);
  ctx.drawImage(cell,n%4*256,Math.floor(n/4)*256);
  manifest.push({name:names[n],cell:n,sourceBounds:p,scale,
    anchors:joints[n].map(([x,y])=>[+(dx+(x-sx)*scale).toFixed(3),+(dy+(y-sy)*scale).toFixed(3)])});
}
mkdirSync(root+'docs/art/suits/vanguard',{recursive:true});
writeFileSync(root+'docs/art/suits/vanguard/maneuver-parts.png',atlas.toBuffer('image/png'));
writeFileSync(root+'art-src/vanguard/maneuver/registration.json',JSON.stringify(manifest,null,2)+'\n');
writeFileSync(root+'illustrated-src/game/vanguard-parts.ts',
  '// Generated by export-vanguard-maneuver.mjs; source anchors live in that exporter.\n'
  +'export const VANGUARD_PARTS = '+JSON.stringify(manifest.map(({name,cell,anchors})=>({name,cell,a:anchors[0],b:anchors[1]})))+' as const;\n');
console.log(JSON.stringify(manifest,null,2));
